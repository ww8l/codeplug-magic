/// The stored byte for a DCS code, or `None` if this radio has no such code.
/// Returns the 1-based table position: index 0 is reserved for "no tone".
pub(crate) fn dcs_to_byte(code: u16, inverted: bool) -> Option<u8> {
    DCS_TABLE
        .iter()
        .position(|&(c, i)| c == code && i == inverted)
        .map(|p| (p + 1) as u8)
}

/// Decode a stored DCS byte back to `(code, inverted)`.
pub(crate) fn byte_to_dcs(byte: u8) -> Option<(u16, bool)> {
    if byte == 0 {
        return None;
    }
    DCS_TABLE.get(byte as usize - 1).copied()
}
