    /// A fifth NMEA sentence is refused as a group; four is written.
    #[test]
    fn nmea_sentences_are_capped_at_four() {
        let mut image = vec![0u8; super::super::layout::IMAGE_LEN];
        image[0x29ACF] = 1; // GGA, the factory default
        let mut s = Map::new();
        for k in ["rmc", "gll", "gsa", "vtg"] {
            s.insert(format!("gps-tx-nmea-sentence-{k}"), Value::Bool(true));
        }
        let (_, notes) = apply(&mut image, &Value::Object(s.clone()));
        assert_eq!(notes.len(), 1, "{notes:?}");
        assert_eq!(&image[0x29ACE..0x29AD4], &[0, 1, 0, 0, 0, 0], "nothing written");
        s.insert("gps-tx-nmea-sentence-gga".into(), Value::Bool(false));
        let (_, notes) = apply(&mut image, &Value::Object(s));
        assert!(notes.is_empty(), "{notes:?}");
        assert_eq!(&image[0x29ACE..0x29AD4], &[1, 0, 1, 1, 1, 0]);
    }

