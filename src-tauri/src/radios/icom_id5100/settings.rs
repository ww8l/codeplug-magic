//! ID-5100 non-channel settings: the field table, read out of a clone image
//! and written back into one.
//!
//! Settings live in the same image the cable clones, so there is no separate
//! settings transport: a read is a download, and a write rides out inside the
//! codeplug program's upload (`carries_profile_settings`), exactly like the
//! UV-5R. The byte rules are Icom's — big-endian integers, space-padded text,
//! off = 0 / on = 1 — and the encoder is the ID-52's own
//! ([`decode_settings_with`] / [`apply_settings_with`]); only the table is this
//! radio's.
//!
//! ## Where the table came from
//!
//! GENERATED by `scratchpad/id5100/vm/gen_table.py` from the measurement files
//! beside it. Every address was measured by driving Icom's CS-5100 inside a VM:
//! move one control, save, diff, one byte per control — first a sweep of every
//! row of every settings page for the address, then a cycle of every option of
//! every dropdown for the stored values, each step's label read off a
//! screenshot of the grid. CS-5100's untouched defaults match the radio's own
//! factory-reset image byte for byte across the whole settings block, which is
//! what makes it trustworthy as an instrument; values it could only show, not
//! prove, are spot-checked on the radio's screen before they ship.

