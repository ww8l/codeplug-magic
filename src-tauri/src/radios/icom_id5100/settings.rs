    /// tables, which the codeplug build owns. (Not "above VOLATILE_BASE": My
    /// Call Sign lives at 0x2215C.)
    #[test]
    fn every_field_is_in_the_settings_area() {
        let memory_end = super::super::layout::BANK_NAMES
            + super::super::layout::BANK_COUNT * super::super::layout::BANK_NAME_LEN;
        for f in ID5100_SETTINGS_FIELDS {
            let at = f.byte as usize;
            assert!(at >= memory_end, "{} at {at:#x} is inside the memory area", f.key);
            assert!(at < super::super::layout::IMAGE_LEN, "{} at {at:#x}", f.key);
        }
    }
